export const getCardsByDifficulty = (difficulty: WordCard['difficulty']) => {
  return vocabularyCards.filter(card => card.difficulty === difficulty);
};

export const getCardsByCategory = (category: string) => {
  return vocabularyCards.filter(card => card.category === category);
};

export const getFavoriteCards = () => {
  return vocabularyCards.filter(card => card.isFavorite);
};

export const getLearnedCards = () => {
  return vocabularyCards.filter(card => card.learned);
};

export const getUnlearnedCards = () => {
  return vocabularyCards.filter(card => !card.learned);
};
