const allCountries: Country[] = [
  ...pinnedCountries,
  ...tier2Countries.sort((a, b) => a.name.localeCompare(b.name)),
  ...tier3Countries.sort((a, b) => a.name.localeCompare(b.name)),
];

const countryMap = new Map<string, Country>(
  allCountries.map((c) => [c.code, c])
);

export function getCountries(): Country[] {
  return allCountries;
}

export function getPinnedCountries(): Country[] {
  return pinnedCountries;
}

export function getNonPinnedCountries(): Country[] {
  const pinnedCodes = new Set(pinnedCountries.map((c) => c.code));
  return allCountries
    .filter((c) => !pinnedCodes.has(c.code))
    .sort((a, b) => a.name.localeCompare(b.name));
}

export function getCountryByCode(code: string): Country | undefined {
  return countryMap.get(code);
}

export function getRegionsForCountry(countryCode: string): Region[] {
  return countryMap.get(countryCode)?.regions ?? [];
}

export function getCountryName(code: string, locale?: string): string {
  if (locale && locale !== 'en') {
    const localized = localizedCountryNames[locale]?.[code];
    if (localized) return localized;
  }
  return countryMap.get(code)?.name ?? code;
}

export function getRegionName(regionCode: string, locale?: string): string {
  if (locale && locale !== 'en') {
    const localized = localizedRegionNames[locale]?.[regionCode];
    if (localized) return localized;
  }
  // Fallback to English name from country data
  for (const country of allCountries) {
    const region = country.regions.find((r) => r.code === regionCode);
    if (region) return region.name;
  }
  return regionCode;
}

export function searchCountries(query: string, locale?: string): Country[] {
  if (!query.trim()) return allCountries;
  const q = query.toLowerCase().trim();
  const localeNames = locale && locale !== 'en' ? localizedCountryNames[locale] : undefined;
  return allCountries.filter(
    (c) =>
      c.name.toLowerCase().includes(q) ||
      c.code.toLowerCase() === q ||
      (localeNames && localeNames[c.code]?.toLowerCase().includes(q))
  );
}
