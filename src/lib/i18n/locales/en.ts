// Widen literal string types so other locale files can provide their own translations
type DeepStringify<T> = {
  readonly [K in keyof T]: T[K] extends readonly string[]
    ? readonly string[]
    : T[K] extends Record<string, unknown>
      ? DeepStringify<T[K]>
      : string;
};

export type Translations = DeepStringify<typeof en>;

// Locale shape for non-English files. Allows partial coverage — missing
// keys fall back to English at runtime, so locales can lag without
// breaking the type checker.
type DeepPartial<T> = T extends Record<string, unknown>
  ? { readonly [K in keyof T]?: DeepPartial<T[K]> }
  : T;
export type PartialTranslations = DeepPartial<Translations>;

export default en;
